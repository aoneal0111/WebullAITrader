"""Offline four-work-order evidence review; never authorizes PAPER or LIVE orders.

Inputs must be reports already generated by the isolated provenance, entry-stage
and hypothetical outcome analyzers. These reports cannot prove broker fills,
protective-stop execution, scanner latency, or profitable strategy performance.
No database, broker, process or strategy is touched.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

SCOPE = "ATLAS_FOUR_WORK_ORDERS_EVIDENCE_V1"
MAX_BYTES = 4_000_000
MAX_CANDIDATES = 12
MAX_ENTRIES = 100
MAX_CASES = 600


def _count(value, maximum):
    if type(value) is not int or not 0 <= value <= maximum:
        raise ValueError("INVALID_AGGREGATE_COUNT")
    return value


def _load(path):
    path = Path(path)
    if path.is_symlink() or not path.is_file() or path.stat().st_size > MAX_BYTES:
        raise ValueError("MISSING_OR_OVERSIZED_REPORT")
    return json.loads(path.read_text(encoding="utf-8-sig"))


def summarize(ledger, recording, entry, micro):
    if not all(isinstance(x, dict) for x in (ledger, recording, entry, micro)):
        raise ValueError("REPORT_OBJECTS_REQUIRED")
    if (ledger.get("scope") != "OFFLINE_ATLAS_PAPER_LEDGER_PROVENANCE_V1"
            or ledger.get("authoritative_ledger_identified") is not False
            or ledger.get("orders") != 0 or ledger.get("network_requests") != 0
            or ledger.get("runtime_modified") is not False):
        raise ValueError("LEDGER_PROVENANCE_SCOPE_UNVERIFIED")
    candidates = ledger.get("candidates")
    if not isinstance(candidates, list) or not 1 <= len(candidates) <= MAX_CANDIDATES:
        raise ValueError("LEDGER_CANDIDATES_UNBOUNDED")
    schema_candidates = sum(
        1 for c in candidates
        if isinstance(c, dict) and c.get("verified_paper_identity") is True
        and c.get("classification") in ("PAPER_SCHEMA_WITH_ORDERS", "EMPTY_PAPER_SCHEMA")
    )
    if (recording.get("scope") != "CLOSED_RECORDING_EVENT_SHAPE_V1"
            or recording.get("authoritative_order_ledger_proven") is not False
            or recording.get("fills_reconciled") is not False
            or recording.get("protective_exits_verified") is not False
            or recording.get("network_requests") != 0
            or recording.get("orders_submitted") != 0
            or recording.get("runtime_modified") is not False):
        raise ValueError("RECORDING_PROVENANCE_SCOPE_UNVERIFIED")
    recording_candidates = _count(recording.get("candidate_event_lines"), 50000)
    if (entry.get("version") != "WARRIOR_PAPER_ENTRY_INTERVALS_V1"
            or entry.get("orders") != 0 or entry.get("network_requests") != 0
            or entry.get("runtime_policy_changed") is not False):
        raise ValueError("ENTRY_REPORT_SCOPE_UNVERIFIED")
    entries = entry.get("entries")
    if not isinstance(entries, list) or len(entries) > MAX_ENTRIES:
        raise ValueError("ENTRY_COUNT_UNBOUNDED")
    exact_source = 0
    timed_orders = 0
    for row in entries:
        if not isinstance(row, dict):
            raise ValueError("INVALID_ENTRY_ROW")
        if (row.get("scanner_to_order_ms") is not None
                or row.get("candidate_signal_to_order_ms") is not None
                or row.get("gateway_snapshot_identity_proven") is not False):
            raise ValueError("UNPROVEN_SCANNER_OR_GATEWAY_JOIN")
        if row.get("source_lineage") == "SOURCE_DECISION_MATCHED":
            exact_source += 1
        elif row.get("source_lineage") != "UNPROVEN":
            raise ValueError("INVALID_SOURCE_LINEAGE")
        ms = row.get("authorization_to_order_ms")
        if ms is not None:
            if type(ms) not in (int, float) or not 0 <= ms <= 86_400_000:
                raise ValueError("INVALID_ENTRY_DURATION")
            timed_orders += 1
    if (micro.get("scope") != "WARRIOR_MICRO_COST_SENSITIVITY_V1"
            or micro.get("source_scope") != "RESEARCH_ONLY_WARRIOR_MICRO_NEXT_OPEN_BARRIER_V1"
            or micro.get("orders") != 0 or micro.get("network_requests") != 0
            or micro.get("production_policy_changed") is not False):
        raise ValueError("MICRO_REPORT_SCOPE_UNVERIFIED")
    cases = _count(micro.get("observed_trigger_runs"), MAX_CASES)
    resolved = _count(micro.get("resolved_cases"), MAX_CASES)
    unresolved = _count(micro.get("unresolved_cases"), MAX_CASES)
    wins = _count(micro.get("resolved_win_count"), MAX_CASES)
    losses = _count(micro.get("resolved_loss_count"), MAX_CASES)
    if resolved + unresolved != cases or wins + losses != resolved:
        raise ValueError("MICRO_OUTCOME_COUNTS_INCONSISTENT")
    scenarios = micro.get("scenarios")
    if not isinstance(scenarios, list) or not 1 <= len(scenarios) <= 12:
        raise ValueError("MICRO_COST_SCENARIOS_MISSING")
    if any(not isinstance(s, dict) or
           s.get("assumed_cost_per_side_per_share") is None or
           s.get("resolved_only_net_r") is None for s in scenarios):
        raise ValueError("MICRO_COST_SCENARIOS_INVALID")
    return {
        "scope": SCOPE,
        "ledger_reconciliation": {
            "classification": "RUNTIME_PROVENANCE_UNVERIFIED",
            "paper_schema_candidates": schema_candidates,
            "candidate_count": len(candidates),
            "closed_recording_event_hints": recording_candidates,
            "broker_confirmed_fills": None,
            "next_evidence": "Match the stopped PAPER runtime campaign to its existing durable ledger and reconcile executions by ID",
        },
        "protective_exits": {
            "classification": "ACTUAL_PROTECTION_UNVERIFIED",
            "recording_stop_execution_proven": False,
            "restart_regression_is_not_runtime_proof": True,
            "next_evidence": "Reconcile entry fill quantity, open stop quantity, partial exits and cancel/replace through restart by order ID",
        },
        "entry_timing": {
            "classification": "SCANNER_TO_ORDER_UNVERIFIED",
            "reconciled_entry_rows": len(entries),
            "exact_source_decision_rows": exact_source,
            "authorization_to_order_timed_rows": timed_orders,
            "scanner_first_seen_proven": False,
            "next_evidence": "Join scanner first-seen, source decision, quote snapshot and submitted order identities without guessing timestamps",
        },
        "strategy_validation": {
            "classification": "RETROSPECTIVE_HYPOTHETICAL_ONLY",
            "hypothetical_trigger_runs": cases,
            "resolved_barrier_cases": resolved,
            "unresolved_or_ambiguous_cases": unresolved,
            "resolved_wins": wins,
            "resolved_losses": losses,
            "cost_scenario_count": len(scenarios),
            "holdout_verified": False,
            "execution_cost_verified": False,
            "strategy_promotion_authorized": False,
            "next_evidence": "Run chronological untouched holdout walk-forward with matched actual PAPER fills, costs and censored outcomes",
        },
        "orders_submitted": 0,
        "network_requests": 0,
        "runtime_modified": False,
        "safe_for_live_promotion": False,
        "limitations": [
            "This report cross-checks existing aggregate research outputs; it does not inspect broker or workstation ledgers.",
            "Historical order-event names do not verify fills or protective stops.",
            "Missing scanner/gateway lineage is never inferred from adjacent decisions.",
            "Retrospective 1R win fraction cannot establish executable out-of-sample profitability.",
        ],
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("ledger", "recording", "entry", "micro"):
        parser.add_argument("--" + name, required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args(argv)
    if args.output.exists():
        parser.error("OUTPUT_MUST_NOT_EXIST")
    result = summarize(*(_load(getattr(args, name)) for name in
                         ("ledger", "recording", "entry", "micro")))
    with args.output.open("x", encoding="utf-8") as stream:
        json.dump(result, stream, indent=2, allow_nan=False)
    print("LEDGER=" + result["ledger_reconciliation"]["classification"])
    print("PROTECTION=" + result["protective_exits"]["classification"])
    print("ENTRY=" + result["entry_timing"]["classification"])
    print("STRATEGY=" + result["strategy_validation"]["classification"])
    print("REPORT=" + str(args.output))


if __name__ == "__main__":
    main()
